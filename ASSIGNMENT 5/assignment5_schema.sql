CREATE TABLE IF NOT EXISTS app_users(user_id VARCHAR(50) PRIMARY KEY,password_text VARCHAR(100) NOT NULL);
CREATE TABLE IF NOT EXISTS wallets(wallet_id INT PRIMARY KEY,balance DECIMAL(12,2) NOT NULL);
CREATE TABLE IF NOT EXISTS students(id INT PRIMARY KEY,name VARCHAR(100) NOT NULL,email VARCHAR(120) NOT NULL);
